export const useI18n = create<I18nState>((set, get) => ({
  lang: 'id',
  setLang: (lang) => { set({ lang }); AsyncStorage.setItem('@ptsss_lang', lang); },
  t: (key, params) => {
    const { lang } = get();
    let text = translations[lang][key] || translations.id[key] || key;
    if (params) {
      Object.entries(params).forEach(([k, v]) => {
        text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
      });
    }
    return text;
  },
}));

AsyncStorage.getItem('@ptsss_lang').then((saved) => {
  if (saved === 'id' || saved === 'en') useI18n.setState({ lang: saved as Lang });
});